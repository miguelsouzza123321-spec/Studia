CREATE TABLE IF NOT EXISTS dev_error_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  method TEXT NOT NULL,
  route TEXT NOT NULL,
  status_code INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_dev_error_logs_created_at
  ON dev_error_logs (created_at DESC);

CREATE TABLE IF NOT EXISTS dev_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  actor_uid UUID,
  actor_role TEXT NOT NULL,
  method TEXT NOT NULL,
  route TEXT NOT NULL,
  status_code INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_dev_audit_logs_created_at
  ON dev_audit_logs (created_at DESC);

ALTER TABLE dev_error_logs ENABLE ROW LEVEL SECURITY;
ALTER TABLE dev_audit_logs ENABLE ROW LEVEL SECURITY;
